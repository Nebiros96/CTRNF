-- CTRNF first web mock-up schema.
-- Apply this file in the Supabase SQL Editor before registering test records.
-- Keep the catalog tables global; personal results are isolated by auth.uid().

create table if not exists public.game_tracks (
  track_id bigint primary key,
  track text not null unique,
  track_clean text not null,
  url text,
  velo_time numeric(10,2),
  dev_time numeric(10,2),
  dev_name text,
  dev_url text,
  track_game text,
  time_wr_glitchless numeric(10,2),
  time_threshold numeric(10,2),
  score_wr bigint,
  score_threshold bigint
);

create table if not exists public.game_skins (
  skin_id bigint primary key,
  skin text not null unique,
  character text not null,
  url text,
  skin_name text,
  skin_type text,
  character_id bigint
);

create table if not exists public.game_characters (
  character text primary key,
  character_id bigint not null unique,
  game_base text,
  mask text,
  url_mask text,
  url_character text
);

create table if not exists public.achievements (
  id bigint primary key,
  name text not null,
  goal bigint not null,
  notes text,
  type text,
  mult numeric(10,3),
  url text,
  description text,
  description_en text
);

create table if not exists public.time_trials (
  id bigint generated by default as identity primary key,
  track_id bigint not null,
  track text not null,
  skin_id bigint not null,
  skin text not null,
  time_raw text not null,
  time_seconds numeric(12,2) not null,
  pb smallint not null default 0,
  delta_pb numeric(12,2) not null default 0,
  captured_at timestamptz not null default now(),
  user_id uuid not null references auth.users(id) on delete cascade
);

create table if not exists public.rally_ring (
  id bigint generated by default as identity primary key,
  track_id bigint not null,
  track text not null,
  skin_id bigint not null,
  skin text not null,
  score bigint not null,
  laps integer not null,
  pb smallint not null default 0,
  delta_pb bigint not null default 0,
  score_mult bigint not null default 0,
  multiplier numeric(12,3) not null default 0,
  notes text not null default '',
  captured_at timestamptz not null default now(),
  user_id uuid not null references auth.users(id) on delete cascade
);

create index if not exists time_trials_user_track_time_idx
  on public.time_trials (user_id, track, time_seconds asc);
create index if not exists rally_ring_user_track_score_idx
  on public.rally_ring (user_id, track, score desc);

alter table public.game_tracks enable row level security;
alter table public.game_skins enable row level security;
alter table public.game_characters enable row level security;
alter table public.achievements enable row level security;
alter table public.time_trials enable row level security;
alter table public.rally_ring enable row level security;

drop policy if exists "Authenticated users can read tracks" on public.game_tracks;
create policy "Authenticated users can read tracks" on public.game_tracks for select to authenticated using (true);
drop policy if exists "Authenticated users can read skins" on public.game_skins;
create policy "Authenticated users can read skins" on public.game_skins for select to authenticated using (true);
drop policy if exists "Authenticated users can read characters" on public.game_characters;
create policy "Authenticated users can read characters" on public.game_characters for select to authenticated using (true);
drop policy if exists "Authenticated users can read achievements" on public.achievements;
create policy "Authenticated users can read achievements" on public.achievements for select to authenticated using (true);

drop policy if exists "Players manage their own time trials" on public.time_trials;
create policy "Players manage their own time trials" on public.time_trials
  for all to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Players manage their own rally results" on public.rally_ring;
create policy "Players manage their own rally results" on public.rally_ring
  for all to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

grant select on public.game_tracks, public.game_skins, public.game_characters, public.achievements to authenticated;
grant select, insert, update, delete on public.time_trials, public.rally_ring to authenticated;
grant usage on schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- Catalogs ship as UTF-8 CSVs in web/public. This staging table keeps the
-- original source columns exactly as-is (including decimal comma strings).
create table if not exists public.catalog_csv_import (
  dataset text not null check (dataset in ('game_tracks', 'game_skins', 'game_characters', 'achievements')),
  row_data jsonb not null
);
alter table public.catalog_csv_import enable row level security;
revoke all on public.catalog_csv_import from anon, authenticated;

create or replace function public.import_ctrnf_catalogs()
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
  insert into public.game_tracks (track_id, track, track_clean, url, velo_time, dev_time, dev_name, dev_url, track_game, time_wr_glitchless, time_threshold, score_wr, score_threshold)
  select (row_data->>'track_id')::bigint, row_data->>'track', row_data->>'track_clean', nullif(row_data->>'url',''),
    replace(nullif(row_data->>'velo_time',''),' ',',')::numeric, replace(nullif(row_data->>'dev_time',''),',','.')::numeric,
    row_data->>'dev_name', nullif(row_data->>'dev_url',''), row_data->>'track_game',
    replace(nullif(row_data->>'time_wr_glitchless',''),',','.')::numeric, replace(nullif(row_data->>'time_threshold',''),',','.')::numeric,
    nullif(row_data->>'score_wr','')::bigint, nullif(row_data->>'score_threshold','')::bigint
  from public.catalog_csv_import where dataset = 'game_tracks'
  on conflict (track_id) do update set track=excluded.track, track_clean=excluded.track_clean, url=excluded.url,
    velo_time=excluded.velo_time, dev_time=excluded.dev_time, dev_name=excluded.dev_name, dev_url=excluded.dev_url,
    track_game=excluded.track_game, time_wr_glitchless=excluded.time_wr_glitchless, time_threshold=excluded.time_threshold,
    score_wr=excluded.score_wr, score_threshold=excluded.score_threshold;

  insert into public.game_skins (skin_id, skin, character, url, skin_name, skin_type, character_id)
  select (row_data->>'skin_id')::bigint, row_data->>'skin', row_data->>'character', nullif(row_data->>'url',''),
    row_data->>'skin_name', row_data->>'skin_type', nullif(row_data->>'character_id','')::bigint
  from public.catalog_csv_import where dataset = 'game_skins'
  on conflict (skin_id) do update set skin=excluded.skin, character=excluded.character, url=excluded.url,
    skin_name=excluded.skin_name, skin_type=excluded.skin_type, character_id=excluded.character_id;

  insert into public.game_characters (character, character_id, game_base, mask, url_mask, url_character)
  select row_data->>'character', (row_data->>'character_id')::bigint, row_data->>'game_base', row_data->>'mask',
    nullif(row_data->>'url_mask',''), nullif(row_data->>'url_character','')
  from public.catalog_csv_import where dataset = 'game_characters'
  on conflict (character) do update set character_id=excluded.character_id, game_base=excluded.game_base,
    mask=excluded.mask, url_mask=excluded.url_mask, url_character=excluded.url_character;

  insert into public.achievements (id, name, goal, notes, type, mult, url, description, description_en)
  select (row_data->>'id')::bigint, row_data->>'name', (row_data->>'goal')::bigint, row_data->>'notes', row_data->>'type',
    replace(nullif(row_data->>'mult',''),',','.')::numeric, nullif(row_data->>'url',''), row_data->>'description', row_data->>'description_en'
  from public.catalog_csv_import where dataset = 'achievements'
  on conflict (id) do update set name=excluded.name, goal=excluded.goal, notes=excluded.notes, type=excluded.type,
    mult=excluded.mult, url=excluded.url, description=excluded.description, description_en=excluded.description_en;
end;
$$;
revoke all on function public.import_ctrnf_catalogs() from public, anon, authenticated;

